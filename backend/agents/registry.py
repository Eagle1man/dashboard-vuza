SPECIALISTS_BY_ID = {a.agent_id: a for a in SPECIALISTS}


def all_agents():
    return [ROUTER] + SPECIALISTS + [ANALYST, GENERALIST]


def get(agent_id):
    if agent_id == "router":
        return ROUTER
    if agent_id in SPECIALISTS_BY_ID:
        return SPECIALISTS_BY_ID[agent_id]
    if agent_id == "analyst":
        return ANALYST
    return GENERALIST


def block_titles():
    """Названия блоков для подсказок роутеру."""
    return {b[0]: b[1] for b in db.BLOCKS}