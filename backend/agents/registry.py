"""
Агенты «Аналитика ректора».

Зачем их несколько, если есть один. Не для имитации команды: разные
агенты получают РАЗНЫЕ документы и разные правила ответа.

- Роутер определяет домен и ничего не отвечает. Отдельный агент нужен
  именно для этого: если специалист ещё и сортирует вопросы, его
  промпт размывается требованием «быть точным» и «быть кратким».
- Специалист по домену получает документы своего блока (doc_block)
  и собственные правила: финансист требует период и единицы, академист
  обязан отличать демо-цифры дашборда от фактов из документов.
- Критик проверяет готовый ответ по фрагментам и не видит рассуждений
  автора. Это отдельный вызов модели со своим контекстом, а не
  «подумай ещё раз» в том же контексте: в том же контексте модель
  продолжает исходные посылки и повторяет те же ошибки.

Каждый агент объявлен данными (системный промпт, блоки, модельная
температура), а не ветвлением в коде — иначе список агентов пришлось
бы искать по всему проекту.
"""
