# -*- coding: utf-8 -*-
"""
Критик агентов.

Смысл в том, что это ОТДЕЛЬНЫЙ вызов модели со своим контекстом.
Просить модель в том же контексте «проверь свой ответ» бессмысленно:
она продолжает исходные посылки и подтверждает саму себя. Критик
получает только фрагменты и готовый текст — ничего больше.

Он не переписывает ответ (это делал бы уже третий агент с вдвое большей
задержкой), а говорит, что именно не подтверждено. Специалист получает
замечание и правит ответ один раз.
"""
from dataclasses import dataclass

from . import registry

SYSTEM = """Ты — критик аналитической системы университета.

Тебе дали фрагменты документов и готовый ответ ассистента. Твоя задача —
проверить, что ответ подтверждён фрагментами.

Проверь по пунктам:
1. Каждоя ли число в ответе действительно есть в фрагментах, с той же
   точностью. Расхождение в знаке процента, в единицах измерения или
   в порядке величины — это ошибка, даже если цифра похожа.
2. Нет ли утверждения, которого во фрагментах нет: добавленного
   «по опыту», «как правило», выводов, которых в тексте нет.
3. Верны ли ссылки [номер] — указывают ли они на фрагменты, где
   действительно есть сказанное.
4. Не перепутаны ли план и факт, прошлый период и текущий.
5. Главное. Подписано ли каждое число источником и есть ли оно во
   фрагментах. Число, которого во фрагментах нет, — выдумка, даже если
   оно выглядит правдоподобно. Правильный ответ либо называет источник,
   либо честно говорит, что в документах университета данных нет.

Если ответ честный и подтверждённый, так и напиши. Если в ответе есть
«в документах не найдено», а в фрагментах ответ есть — это тоже ошибка,
но противоположная.

Отвечай СТРОГО тремя строками, без пояснений:
ВЕРДИКТ: ОК
ПРОБЛЕМА: -
ИСПРАВЛЕНИЕ: -

или

ВЕРДИКТ: НУЖНО ИСПРАВИТЬ
ПРОБЛЕМА: <что именно не так, кратко>
ИСПРАВЛЕНИЕ: <что надо сделать, одной фразой>"""


@dataclass
class Verdict:
    ok: bool
    problem: str = ""
    fix: str = ""
    raw: str = ""
    ran: bool = True
    reason: str = ""

    def as_dict(self):
        return {"ok": self.ok, "problem": self.problem, "fix": self.fix,
                "ran": self.ran, "reason": self.reason,
                "raw": self.raw[:600]}


def _parse(text: str) -> Verdict:
    verdict, problem, fix = "", "", ""
    for line in (text or "").splitlines():
        line = line.strip()
        if line.upper().startswith("ВЕРДИКТ"):
            verdict = line.split(":", 1)[1].strip() if ":" in line else ""
        elif line.upper().startswith("ПРОБЛЕМА"):
            problem = line.split(":", 1)[1].strip() if ":" in line else ""
        elif line.upper().startswith("ИСПРАВЛЕНИЕ"):
            fix = line.split(":", 1)[1].strip() if ":" in line else ""
    # Прочерк в шаблоне — это «поля нет», а не значение «-». Иначе
    # «ПРОБЛЕМА: -» превращается в текст замечания, который потом
    # попадает в подсказку специалисту при правке ответа.
    problem = "" if problem in ("-", "—", "нет", "нет.") else problem
    fix = "" if fix in ("-", "—", "нет", "нет.") else fix
    if not verdict:
        # Модель не попала в формат. Молча считать это «ОК» нельзя —
        # тогда критика можно обойти, просто ответив не по формату.
        # Молча считать «НЕ ОК» тоже нельзя: это добавит выдуманное
        # замечание. Поэтому результат неизвестен, и это видно.
        return Verdict(ok=True, raw=text or "", reason="не удалось разобрать вердикт")
    ok = "НУЖНО" not in verdict.upper() and "НЕ ОК" not in verdict.upper()
    return Verdict(ok=ok, problem=problem, fix=fix, raw=text or "")


def review(answer_text, chunks, model=None):
    from .. import llm
    context = llm.build_context(chunks) if chunks else "(фрагменты не найдены)"
    user = ("ФРАГМЕНТЫ ДОКУМЕНТОВ:\n\n" + context +
            "\n\n---\nОТВЕТ АССИСТЕНТА:\n\n" + (answer_text or "(пусто)") +
            "\n\nПРОВЕРЬ ОТВЕТ ПО ФРАГМЕНТАМ.")
    text, meta = llm.chat(SYSTEM, user, model=model, temperature=0.0,
                          num_predict=260)
    if not meta.get("ok"):
        return Verdict(ok=True, ran=False, reason=meta.get("reason") or "модель недоступна")
    return _parse(text)